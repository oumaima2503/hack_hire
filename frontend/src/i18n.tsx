const DICTS: Record<Lang, Record<Key, string>> = { en, fr, ar }
export const LANG_NAMES: Record<Lang, string> = { en: 'English', fr: 'Français', ar: 'العربية' }
export const LANG_FLAGS: Record<Lang, string> = { en: '🇬🇧', fr: '🇫🇷', ar: '🇲🇦' }

interface Ctx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: Key, vars?: Record<string, string | number>) => string
}
const I18nContext = createContext<Ctx | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem('myrugy.lang') as Lang | null
      if (saved && saved in DICTS) return saved
    } catch {
      /* ignore */
    }
    return 'en'
  })

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
    try {
      localStorage.setItem('myrugy.lang', lang)
    } catch {
      /* ignore */
    }
  }, [lang])

  const t = useCallback(
    (key: Key, vars?: Record<string, string | number>) =>
      (DICTS[lang][key] ?? en[key]).replace(/\{(\w+)\}/g, (_, k) => String(vars?.[k] ?? `{${k}}`)),
    [lang],
  )

  return <I18nContext.Provider value={{ lang, setLang: setLangState, t }}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n outside provider')
  return ctx
}

export type { Key as I18nKey }
